#!/usr/bin/env python3
"""Build and validate the file://-compatible vLLM course manifest."""
import argparse
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parent.parent
HEADER = "/* Generated by scripts/build_course_data.py from courses.json. */\n"
SOURCE = ROOT / "courses.json"
OUTPUT = ROOT / "courses-data.js"
CHAPTER_RE = re.compile(r"^[0-9]{2}\.html$")


def build():
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    chapters = data.get("chapters")
    categories = data.get("categories")
    if not isinstance(chapters, list) or not chapters:
        raise ValueError("chapters must be a nonempty array")
    if data.get("chapterCount") != len(chapters):
        raise ValueError("chapterCount differs from chapters length")
    if data.get("schemaVersion") != 2:
        raise ValueError("schemaVersion must be 2")
    if not isinstance(categories, list) or not categories:
        raise ValueError("categories must be a nonempty array")

    category_ids = set()
    for category in categories:
        if not isinstance(category, dict):
            raise ValueError("category must be an object")
        category_id = category.get("id")
        if not isinstance(category_id, str) or not re.fullmatch(r"[a-z0-9-]+", category_id):
            raise ValueError("category id must be a lowercase slug")
        if category_id in category_ids:
            raise ValueError("duplicate category id: " + category_id)
        if not isinstance(category.get("title"), str) or not category["title"].strip():
            raise ValueError("category title is required: " + category_id)
        if not isinstance(category.get("order"), int):
            raise ValueError("category order must be an integer: " + category_id)
        category_ids.add(category_id)

    seen_numbers = set()
    seen_files = set()
    for chapter in chapters:
        if not isinstance(chapter, dict):
            raise ValueError("chapter must be an object")
        number = chapter.get("num")
        filename = chapter.get("file")
        if not isinstance(number, str) or not re.fullmatch(r"[0-9]{2}", number):
            raise ValueError("chapter number must be a two-digit string")
        if number in seen_numbers:
            raise ValueError("duplicate chapter number: " + number)
        if not isinstance(filename, str) or not CHAPTER_RE.fullmatch(filename):
            raise ValueError("invalid local chapter path: " + str(filename))
        if filename != number + ".html":
            raise ValueError("chapter file must match its number: " + number)
        if filename in seen_files or not (ROOT / filename).is_file():
            raise ValueError("duplicate or missing chapter file: " + filename)
        if chapter.get("category") not in category_ids:
            raise ValueError("unknown category for chapter " + number)
        if chapter.get("level") not in {"入门", "进阶", "高级", "综合"}:
            raise ValueError("invalid level for chapter " + number)
        if not isinstance(chapter.get("durationMinutes"), int) or chapter["durationMinutes"] < 1:
            raise ValueError("durationMinutes must be a positive integer: " + number)
        if not isinstance(chapter.get("summary"), str) or not chapter["summary"].strip():
            raise ValueError("summary is required: " + number)
        for field in ("topics", "learningObjectives", "tags", "prerequisites"):
            if not isinstance(chapter.get(field), list):
                raise ValueError(field + " must be an array: " + number)
        if len(chapter["learningObjectives"]) < 2:
            raise ValueError("at least two learning objectives are required: " + number)
        if any(not isinstance(item, str) or not item.strip() for item in chapter["tags"]):
            raise ValueError("tags must contain nonempty strings: " + number)
        if number in chapter["prerequisites"]:
            raise ValueError("chapter cannot depend on itself: " + number)
        seen_numbers.add(number)
        seen_files.add(filename)

    known_numbers = {chapter["num"] for chapter in chapters}
    for chapter in chapters:
        unknown = set(chapter["prerequisites"]) - known_numbers
        if unknown:
            raise ValueError("unknown prerequisite(s) for " + chapter["num"] + ": " + ", ".join(sorted(unknown)))

    return HEADER + "window.VLLM_COURSES = " + json.dumps(data, ensure_ascii=False, indent=2) + ";\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        expected = build()
        if args.check:
            if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != expected:
                print("outdated courses-data.js; regenerate it", file=sys.stderr)
                return 1
            print("manifest is synchronized")
        else:
            OUTPUT.write_text(expected, encoding="utf-8")
            print("manifest regenerated")
        return 0
    except (OSError, ValueError, TypeError, json.JSONDecodeError) as error:
        print("manifest validation failed: " + str(error), file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
