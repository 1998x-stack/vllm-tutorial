#!/usr/bin/env python3
"""Build and verify the file://-compatible catalog manifest."""
import argparse
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parent.parent
HEADER = "/* Generated by scripts/build_course_data.py from courses.json. */\n"
SOURCE = ROOT / "courses.json"
OUTPUT = ROOT / "courses-data.js"


def build():
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    chapters = data.get("chapters")
    if not isinstance(chapters, list) or not chapters:
        raise ValueError("chapters must be a nonempty array")
    if data.get("chapterCount") != len(chapters):
        raise ValueError("chapterCount differs from chapters length")
    seen = set()
    for chapter in chapters:
        if not isinstance(chapter, dict):
            raise ValueError("chapter must be an object")
        number = chapter.get("num")
        filename = chapter.get("file")
        if not isinstance(number, str) or not isinstance(filename, str):
            raise ValueError("chapter number and filename must be strings")
        if not re.fullmatch(r"[0-9]{2}\.html", filename) or filename != number + ".html":
            raise ValueError("invalid local chapter path")
        if filename in seen or not (ROOT / filename).is_file():
            raise ValueError("duplicate or missing chapter file: " + filename)
        seen.add(filename)
    return HEADER + "window.VLLM_COURSES = " + json.dumps(data, ensure_ascii=False, indent=2) + ";\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        expected = build()
        if args.check:
            if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != expected:
                print("outdated courses-data.js; regenerate it", file=sys.stderr)
                return 1
            print("manifest is synchronized")
        else:
            OUTPUT.write_text(expected, encoding="utf-8")
            print("manifest regenerated")
        return 0
    except (OSError, ValueError, TypeError) as error:
        print("manifest validation failed: " + str(error), file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
